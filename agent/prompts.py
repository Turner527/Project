GRAIN_WORDS = {"day": "дни", "week": "недели", "month": "месяцы", "quarter": "кварталы", "year": "годы"}


def catalog_text(table) -> str:
    """Каталог отчёта для промпта: период, показатели, измерения. Строится кодом, поэтому ему можно доверять."""
    s = table.summary()
    parts = [f"Доступные данные: источник «{table.source}»"]
    if table.grain is not None:
        parts.append(f"период с {s['first_period']} по {s['last_period']} (детализация: {GRAIN_WORDS[table.grain]})")
    metrics = []
    for m in table.spec.metrics[:30]:
        label = m.name + (f" ({m.unit})" if m.unit else "")
        metrics.append(label + (", есть план" if m.has_plan else ""))
    parts.append("показатели: " + "; ".join(metrics))
    dims = [f"{d} ({len(table.dim_values[d])}: {', '.join(table.dim_values[d][:6])}"
            f"{', …' if len(table.dim_values[d]) > 6 else ''})" for d in table.dims[:6]]
    parts.append("измерения: " + ("; ".join(dims) if dims else "нет"))
    return "; ".join(parts) + "."


def build_system_prompt(table=None) -> str:
    """Системный промпт плюс каталог активного отчёта."""
    return SYSTEM_PROMPT if table is None else f"{SYSTEM_PROMPT}\n\n{catalog_text(table)}"
